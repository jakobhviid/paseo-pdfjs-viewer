#!/usr/bin/env node
// Embeds the pdfjs-dist runtime into a module the plugin's server code serves to the app.
//
// Paseo evaluates plugin server bundles with its own `require`, outside the plugin directory, so
// server code cannot read node_modules files at runtime. Everything the viewer needs is therefore
// generated into server/generated/ when the plugin is prepared (`build` in paseo-plugin.json, or
// `npm install` during development).
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pdfjsRoot = path.join(root, "node_modules", "pdfjs-dist");
const outDir = path.join(root, "server", "generated");

function readText(relative) {
  return readFileSync(path.join(pdfjsRoot, relative), "utf8");
}

function readBase64Directory(relative, include) {
  const directory = path.join(pdfjsRoot, relative);
  const files = {};
  for (const name of readdirSync(directory).sort()) {
    if (!include(name)) continue;
    files[name] = readFileSync(path.join(directory, name)).toString("base64");
  }
  return files;
}

const IMAGE_TYPES = { ".svg": "image/svg+xml", ".gif": "image/gif", ".png": "image/png" };

/** The stylesheet references web/images/*; the app has no URL for them, so inline them. */
function inlineCssImages(css) {
  return css.replace(/url\((["']?)images\/([^"')]+)\1\)/g, (match, _quote, name) => {
    const type = IMAGE_TYPES[path.extname(name)];
    if (!type) return match;
    const data = readFileSync(path.join(pdfjsRoot, "web", "images", name)).toString("base64");
    return `url("data:${type};base64,${data}")`;
  });
}

const { version } = JSON.parse(readText("package.json"));

const runtime = {
  pdf: readText("build/pdf.min.mjs"),
  viewer: readText("web/pdf_viewer.mjs"),
  worker: readText("build/pdf.worker.min.mjs"),
  css: inlineCssImages(readText("web/pdf_viewer.css")),
};

// Keys match PDF.js's BinaryDataFactory `kind` values.
const binary = {
  cMapUrl: readBase64Directory("cmaps", (name) => name.endsWith(".bcmap")),
  standardFontDataUrl: readBase64Directory("standard_fonts", (name) => !name.startsWith("LICENSE")),
  // Image decoders only: the QuickJS scripting sandbox is not enabled, and the ICC module is used
  // only when the worker fetches files itself.
  wasmUrl: readBase64Directory("wasm", (name) => name === "jbig2.wasm" || name === "openjpeg.wasm"),
};

mkdirSync(outDir, { recursive: true });
const banner =
  `// Generated by scripts/embed-pdfjs.mjs from pdfjs-dist ${version}. Do not edit.\n` +
  "// PDF.js is licensed under Apache-2.0; see node_modules/pdfjs-dist/LICENSE and THIRD_PARTY_NOTICES.md.\n";
writeFileSync(
  path.join(outDir, "pdfjs-assets.js"),
  `${banner}export const pdfjsVersion = ${JSON.stringify(version)};\n` +
    `export const runtime = ${JSON.stringify(runtime)};\n` +
    `export const binary = ${JSON.stringify(binary)};\n`,
);
writeFileSync(
  path.join(outDir, "pdfjs-assets.d.ts"),
  `${banner}export declare const pdfjsVersion: string;\n` +
    'export declare const runtime: Readonly<Record<"pdf" | "viewer" | "worker" | "css", string>>;\n' +
    "export declare const binary: Readonly<\n" +
    '  Record<"cMapUrl" | "standardFontDataUrl" | "wasmUrl", Readonly<Record<string, string>>>\n' +
    ">;\n",
);

const count = (files) => Object.keys(files).length;
console.log(
  `Embedded pdfjs-dist ${version}: ${count(binary.cMapUrl)} CMaps, ` +
    `${count(binary.standardFontDataUrl)} standard fonts, ${count(binary.wasmUrl)} wasm modules.`,
);
