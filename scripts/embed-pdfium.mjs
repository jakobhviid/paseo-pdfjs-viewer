#!/usr/bin/env node
// Embeds PDFium (@hyzyla/pdfium) into a module the plugin's server code hands to its render worker.
//
// The iOS panel's pages are rendered by PDFium in a worker thread. Paseo evaluates plugin server
// bundles outside the plugin directory, so neither the bundle nor a worker it starts can load files
// from node_modules at runtime. As with PDF.js (scripts/embed-pdfjs.mjs), the CommonJS build's source
// and the wasm binary are generated into server/generated/ when the plugin is prepared.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pdfiumRoot = path.join(root, "node_modules", "@hyzyla", "pdfium");
const outDir = path.join(root, "server", "generated");

const { version } = JSON.parse(readFileSync(path.join(pdfiumRoot, "package.json"), "utf8"));
// The CommonJS build loads only Node built-ins and takes the wasm through `instantiateWasm`.
const source = readFileSync(path.join(pdfiumRoot, "dist", "index.cjs"), "utf8");
const wasm = readFileSync(path.join(pdfiumRoot, "dist", "pdfium.wasm")).toString("base64");

mkdirSync(outDir, { recursive: true });
const banner =
  `// Generated by scripts/embed-pdfium.mjs from @hyzyla/pdfium ${version}. Do not edit.\n` +
  "// @hyzyla/pdfium is MIT-licensed and PDFium BSD-3-Clause and Apache-2.0; see THIRD_PARTY_NOTICES.md.\n";
writeFileSync(
  path.join(outDir, "pdfium-assets.js"),
  `${banner}export const pdfiumVersion = ${JSON.stringify(version)};\n` +
    `export const pdfiumSource = ${JSON.stringify(source)};\n` +
    `export const pdfiumWasm = ${JSON.stringify(wasm)};\n`,
);
writeFileSync(
  path.join(outDir, "pdfium-assets.d.ts"),
  `${banner}export declare const pdfiumVersion: string;\n` +
    "export declare const pdfiumSource: string;\n" +
    "/** pdfium.wasm, base64. */\n" +
    "export declare const pdfiumWasm: string;\n",
);

console.log(
  `Embedded @hyzyla/pdfium ${version}: ${Math.round(source.length / 1024)} KB of code, ` +
    `${Math.round((wasm.length * 3) / 4 / 1024)} KB of wasm.`,
);
